#!/usr/bin/env python3
"""Does a linear regression recover the error rates of a device from random mirror circuits? A test with known answers: no device.

    QSIM=path/to/qsim ML=path/to/ml python3 scripts/rates_sim.py [--circuits 160] [--seed 1] [--shots 0]

A 5-qubit line is given known depolarizing rates (one per qubit for one-qubit gates, one per pair for `cz`) and known read-out errors.
Random mirror circuits (a random circuit of `sx`, `x` and `cz` on neighbouring pairs, then its inverse) of different depths and
different use of the pairs are run on `qsim`'s exact density matrix; each one's survival S (the chance of reading all zeros, with the read-out
error applied) is what a device would measure. To first order S is a product over the gates (1 - lambda_g)^n_g times a read-out
constant, so log S is linear in the gate counts n_g: `ml fit --model linear --l2 ...` on a CSV of those counts and log S estimates
every lambda_g, from which the depolarizing probability follows (lambda = 2p/3 for one qubit, 4p/5 for two: a depolarized qubit
that is measured can still read 0).

The script prints, per gate type, the true probability, the estimate and the relative error, and the mean of the relative
errors. With --shots N the survival is a sample of N shots, as a device returns, so the regression has the noise a real run would have.
The regression's job is judged against the truth, not against the simulator it was generated by in some other way: nothing is fitted to the
count of a gate that the circuits do not use, and a rate the circuits cannot tell apart is reported by the spread of its estimate over seeds (--seeds).
"""
import argparse
import csv
import json
import math
import os
import random
import subprocess
import sys
import tempfile

N = 5
DEN = 1_000_000
TRUE_1Q = [0.0004, 0.0006, 0.0003, 0.0008, 0.0005]          # depolarizing probability after sx or x, per qubit
TRUE_2Q = [0.006, 0.010, 0.004, 0.015]                      # after cz, for the pairs (0,1) (1,2) (2,3) (3,4)
TRUE_RO = [(0.010, 0.020), (0.015, 0.025), (0.008, 0.018), (0.030, 0.040), (0.012, 0.022)]   # P(read 1 | 0), P(read 0 | 1)


def circuit(rnd, layers, cz_probability=0.6):
    """(forward ops, counts) of a random circuit of `layers` layers: each layer is a random native gate on every qubit, then cz on a random set of disjoint neighbouring pairs."""
    ops, n1, n2 = [], [0] * N, [0] * (N - 1)
    for _ in range(layers):
        for q in range(N):
            if rnd.random() < 0.7:      # a qubit that is left out of a layer has no gate and no gate noise: without this every qubit
                g = rnd.choice(["sx", "sx", "x"])   # has the same count of one-qubit gates in every circuit, and their rates cannot be told apart
                ops.append((g, q, 0))
                n1[q] += 1
        pairs = [p for p in range(N - 1) if rnd.random() < cz_probability]
        used = set()
        for p in pairs:
            if p not in used and p + 1 not in used:
                ops.append(("cz", p, p + 1))
                used |= {p, p + 1}
                n2[p] += 1
    return ops, n1, n2


def inverse(ops):
    # sx^-1 is rx(-pi/2); x and cz are their own inverses
    return [("sx_inv" if g == "sx" else g, a, b) for g, a, b in reversed(ops)]


def text(ops):
    lines = [f"dm {N}"]
    for q in range(N):
        lines.append(f"gate1err {q} {round(TRUE_1Q[q] * DEN)} {DEN}")
    for p in range(N - 1):
        lines.append(f"gate2err {p} {p + 1} {round(TRUE_2Q[p] * DEN)} {DEN}")
    for g, a, b in ops:
        if g == "sx":
            lines.append(f"rx {a} 1 2")
        elif g == "sx_inv":
            lines.append(f"rx {a} -1 2")
        elif g == "x":
            lines.append(f"x {a}")
        elif g == "cz":
            lines.append(f"cz {a} {b}")
    lines.append("probs")
    return "\n".join(lines) + "\n"


def survival(qsim, ops):
    out = subprocess.run([qsim], input=text(ops), capture_output=True, text=True, check=True).stdout
    probs = {l.split()[1]: float(l.split()[2]) for l in out.splitlines() if l.startswith("prob ")}
    s = 0.0
    for bits, p in probs.items():
        w = p
        for q in range(N):
            bit = bits[::-1][q]                       # qubit 0 is the rightmost character
            w *= (1 - TRUE_RO[q][0]) if bit == "0" else TRUE_RO[q][1]
        s += w
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--circuits", type=int, default=160)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--shots", type=int, default=0, help="0: the exact survival; N: a sample of N shots")
    ap.add_argument("--l2", default="0.001")
    ap.add_argument("--oneq", action="store_true", help="add circuits with one-qubit gates only (every third)")
    ap.add_argument("--scale1", type=float, default=1.0, help="multiply the true one-qubit rates (their signal is small next to the two-qubit rates')")
    args = ap.parse_args()
    for q in range(N):
        TRUE_1Q[q] *= args.scale1
    qsim, ml = os.environ.get("QSIM", "qsim"), os.environ.get("ML", "ml")
    rnd = random.Random(args.seed)
    rows = []
    for i in range(args.circuits):
        if args.oneq and i % 3 == 0:        # every third circuit: no cz, many one-qubit gates, so that their small rates show above the noise
            fwd, n1, n2 = circuit(rnd, rnd.randint(10, 60), 0.0)
        else:
            fwd, n1, n2 = circuit(rnd, rnd.randint(1, 12))
        ops = fwd + inverse(fwd)
        s = survival(qsim, ops)
        if args.shots:
            k = sum(1 for _ in range(args.shots) if rnd.random() < s)   # the shots that read all zeros
            s = max(k, 0.5) / args.shots
        # each gate appears twice (forward and inverse)
        rows.append([2 * c for c in n2] + [2 * c for c in n1] + [math.log(s)])
    names = [f"cz{p}{p + 1}" for p in range(N - 1)] + [f"g1_{q}" for q in range(N)] + ["logS"]
    d = tempfile.mkdtemp(prefix="rates-")
    path = os.path.join(d, "mirror.csv")
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(names)
        for r in rows:
            w.writerow([f"{x:.17g}" if isinstance(x, float) else x for x in r])
    model = os.path.join(d, "rates.ml")
    r = subprocess.run([ml, "fit", "--model", "linear", "--l2", args.l2, "--target", "logS", "--output", model, path], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"ml fit failed ({r.returncode}):\n{r.stdout}\n{r.stderr}")
    doc = json.loads(r.stdout)
    coef = {c["name"]: float(c["value"]) for c in doc["data"]["summary"]["coefficients"]}
    intercept = float(doc["data"]["summary"]["intercept"])
    print(f"{args.circuits} circuits, {'exact survival' if not args.shots else str(args.shots) + ' shots'}, ml fit --model linear --l2 {args.l2}; intercept {intercept:.4f} (read-out: log of the product of the survivals {sum(math.log((1 - a)) for a, _ in TRUE_RO):.4f})")
    print(f"{'rate':8} {'true p':>9} {'estimate':>9} {'rel. error':>10}")
    errs = []
    for p in range(N - 1):
        lam = 1 - math.exp(coef[f"cz{p}{p + 1}"])
        est = lam * 5 / 4
        errs.append(abs(est - TRUE_2Q[p]) / TRUE_2Q[p])
        print(f"{'cz ' + str(p) + '-' + str(p + 1):8} {TRUE_2Q[p]:9.5f} {est:9.5f} {errs[-1]:10.1%}")
    for q in range(N):
        lam = 1 - math.exp(coef[f"g1_{q}"])
        est = lam * 3 / 2
        errs.append(abs(est - TRUE_1Q[q]) / TRUE_1Q[q])
        print(f"{'1q ' + str(q):8} {TRUE_1Q[q]:9.5f} {est:9.5f} {errs[-1]:10.1%}")
    print(f"mean relative error: two-qubit {sum(errs[:N - 1]) / (N - 1):.1%}, one-qubit {sum(errs[N - 1:]) / N:.1%}")


if __name__ == "__main__":
    main()
